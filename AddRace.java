    private void ConfirmAddRaceActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_ConfirmAddRaceActionPerformed
        try {
            int newId = Integer.parseInt(raceId.getText().trim());
            int lapAmount = Integer.parseInt(LapRace.getText().trim());
            int day = Integer.parseInt(dayRace.getText().trim());
            int month = Integer.parseInt(monthRace.getText().trim());
            int year = Integer.parseInt(yearRace.getText().trim());
            int idTrack = Integer.parseInt(TrackRace.getText().trim());

            java.sql.Date dateSQL = java.sql.Date.valueOf(String.format("%04d-%02d-%02d", year, month, day));

            DefaultTableModel model = (DefaultTableModel) positionTable.getModel();
            java.util.List<String[]> list = new java.util.ArrayList<>();

            for (int i = 0; i < model.getRowCount(); i++) {
                String pos = model.getValueAt(i, 0).toString(); 
                String id = model.getValueAt(i, 1).toString(); 
                list.add(new String[]{ pos, id });
            }

            if (ConexionDB.Add(lapAmount, newId, dateSQL, idTrack, list)) {
                JOptionPane.showMessageDialog(this, "Carrera registrada correctamente.");
                this.setVisible(false);
            } else {
                JOptionPane.showMessageDialog(this, "Hubo un error al registrar la carrera.");
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al procesar la carrera. Verificá los campos.");
        }
    }// GEN-LAST:event_ConfirmAddRaceActionPerformed
    

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String position = jTextField3.getText().trim();
        String id = jTextField4.getText().trim();
        String name = jTextField2.getText().trim();

        if (name.isEmpty() || position.isEmpty() || id.isEmpty()) { // Validar campos vacíos
            JOptionPane.showMessageDialog(this, "Todos los campos deben estar completos.");
            return;
        }

        try { 
            int pos = Integer.parseInt(position);
            if (pos < 1) {
                JOptionPane.showMessageDialog(this, "La posición debe ser mayor a 0.");
                return;
            }

            DefaultTableModel model = (DefaultTableModel) positionTable.getModel();
            model.addRow(new Object[]{pos, id, name});
        
            TableRowSorter<DefaultTableModel> sorter = new TableRowSorter<>((DefaultTableModel) positionTable.getModel());
            positionTable.setRowSorter(sorter);
            sorter.toggleSortOrder(0);

            jTextField2.setText("");
            jTextField3.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La posición debe ser un número válido.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

